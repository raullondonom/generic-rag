#!/usr/bin/env bash
# Builds the application image (optional), loads it into kind and applies the Kubernetes manifests.
# Works with a cloud cluster too (K8S_OVERLAY=cloud, BUILD=0). The settings come from .env (see env.sh):
#
#   ./deploy/k8s/scripts/deploy.sh                       # overlay and namespace from .env (default local, rag)
#   K8S_OVERLAY=cloud BUILD=0 ./deploy/k8s/scripts/deploy.sh
#   RENDER_ONLY=1 ./deploy/k8s/scripts/deploy.sh       # print the manifests, apply nothing
#
# The manifests are rendered through deploy/k8s/.generated/ (gitignored), which adds to the chosen overlay:
# the namespace, the image, the GPU patches and the application settings of .env (every key of
# base/configmap.yaml that .env defines, except the in-cluster addresses). K8S_CONFIG_FROM_ENV=false
# applies the manifests' values only.
set -euo pipefail

# shellcheck source=env.sh
. "$(dirname "${BASH_SOURCE[0]}")/env.sh"
BUILD="${BUILD:-1}"
CONFIG_FROM_ENV="$(setting CONFIG_FROM_ENV K8S_CONFIG_FROM_ENV true)"
K8S_DIR="$REPO_ROOT/deploy/k8s"
GEN="$K8S_DIR/.generated"

[ -d "$K8S_DIR/overlays/$OVERLAY" ] || { echo "Unknown overlay '$OVERLAY' (deploy/k8s/overlays/)" >&2; exit 1; }

# ---------------------------------------------------------------- rendered kustomization
rm -rf "$GEN"
mkdir -p "$GEN"

# Image reference: name[:tag] (a registry port is not a tag)
image_name="$IMAGE" image_tag=latest
if [[ "${IMAGE##*/}" == *:* ]]; then image_name="${IMAGE%:*}"; image_tag="${IMAGE##*:}"; fi

# Settings from .env: every key of the base ConfigMap that .env defines. The in-cluster addresses are the
# Services, and the deepseek-* overlays own the provider (that is what they are for).
skip=" QDRANT_URL EMBEDDING_URL OLLAMA_URL DOCS_PATH QDRANT_REPLICATION_FACTOR QDRANT_WRITE_CONSISTENCY QDRANT_SHARDS DB_POOL_MAX "
case "$OVERLAY" in deepseek-*) skip="$skip LLM_PROVIDER " ;; esac
data=()
if [ "$CONFIG_FROM_ENV" = true ] && [ -f "$ENV_FILE" ]; then
  for key in $(sed -n 's/^  \([A-Z][A-Z0-9_]*\):.*/\1/p' "$K8S_DIR/base/configmap.yaml"); do
    case "$skip" in *" $key "*) continue ;; esac
    grep -q "^${key}=" "$ENV_FILE" || continue
    # YAML double-quoted string: backslashes and quotes escaped (a regex like CACHE_SKIP_PATTERN has both)
    value="$(env_file_get "$key" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')"
    data+=("  $key: \"$value\"")
  done
fi
overrides=${#data[@]}
{
  echo "apiVersion: v1"
  echo "kind: ConfigMap"
  echo "metadata:"
  echo "  name: rag-config"
  # An empty "data:" is null, and a null in a strategic merge patch deletes the whole field
  if [ "$overrides" -gt 0 ]; then echo "data:"; printf '%s\n' "${data[@]}"; else echo "data: {}"; fi
} > "$GEN/config-from-env.yaml"

{
  echo "# Generated by deploy/k8s/scripts/deploy.sh: do not edit (rendered again on every deploy)."
  echo "apiVersion: kustomize.config.k8s.io/v1beta1"
  echo "kind: Kustomization"
  echo "namespace: $NAMESPACE"
  echo "resources:"
  echo "  - ../overlays/$OVERLAY"
  echo "images:"
  echo "  - name: genric-rag-app"
  echo "    newName: $image_name"
  echo "    newTag: \"$image_tag\""
  case "$GPU" in
    nvidia)
      tei="$(env_file_get TEI_GPU_IMAGE)"
      echo "  - name: ghcr.io/huggingface/text-embeddings-inference"
      echo "    newTag: \"$( [ -n "$tei" ] && echo "${tei##*:}" || echo 89-1.9 )\""
      ;;
  esac
  echo "patches:"
  echo "  - path: config-from-env.yaml"
  echo "    target: {kind: ConfigMap, name: rag-config}"
  case "$GPU" in
    nvidia)
      echo "  - path: embeddings-gpu-nvidia.patch.yaml"
      echo "    target: {kind: Deployment, name: embeddings}"
      [[ "$OVERLAY" == deepseek-* ]] || {
        echo "  - path: ollama-gpu-nvidia.patch.yaml"
        echo "    target: {kind: Deployment, name: ollama}"
      }
      ;;
    amd)
      [[ "$OVERLAY" == deepseek-* ]] || {
        echo "  - path: ollama-gpu-amd.patch.yaml"
        echo "    target: {kind: Deployment, name: ollama}"
      }
      ;;
  esac
} > "$GEN/kustomization.yaml"
# The optional patches are written for `kubectl patch` (spec only); a Kustomize patch file also needs the
# object it applies to
gpu_patch() {  # gpu_patch <file> <deployment>
  { printf 'apiVersion: apps/v1\nkind: Deployment\nmetadata:\n  name: %s\n' "$2"
    grep -v '^#' "$K8S_DIR/optional/$1"; } > "$GEN/$1"
}
case "$GPU" in
  nvidia) gpu_patch embeddings-gpu-nvidia.patch.yaml embeddings; gpu_patch ollama-gpu-nvidia.patch.yaml ollama ;;
  amd) gpu_patch ollama-gpu-amd.patch.yaml ollama ;;
esac
echo "Overlay '$OVERLAY' in namespace '$NAMESPACE', image $image_name:$image_tag, GPU $GPU, $overrides setting(s) from .env"

# RENDER_ONLY=1: print what would be applied and stop (no build, no cluster needed)
if [ "${RENDER_ONLY:-0}" = 1 ]; then
  kubectl kustomize "$GEN"
  exit 0
fi

# ---------------------------------------------------------------- image
if [ "$BUILD" = 1 ]; then
  echo "Building $IMAGE..."
  docker build -t "$IMAGE" "$REPO_ROOT/app"
fi

# kind load fails with Docker Desktop's containerd image store when an image index lists platforms that
# are not on disk ("content digest ... not found"): import only the node's platform instead.
load_image() {
  if kind load docker-image "$1" --name "$CLUSTER" >/dev/null 2>&1; then return 0; fi
  local platform="linux/$(docker version --format '{{.Server.Arch}}')"
  local node
  for node in $(kind get nodes --name "$CLUSTER"); do
    docker save --platform "$platform" "$1" \
      | docker exec -i "$node" ctr --namespace=k8s.io images import --snapshotter=overlayfs - >/dev/null
  done
}

if command -v kind >/dev/null 2>&1 && kind get clusters 2>/dev/null | grep -qx "$CLUSTER"; then
  echo "Loading images into kind cluster '$CLUSTER'..."
  images=(
    "$IMAGE"
    postgres:18.4-alpine
    qdrant/qdrant:v1.19.2
    ghcr.io/huggingface/text-embeddings-inference:cpu-1.9
    nginx:1.28-alpine
  )
  case "$OVERLAY" in
    deepseek-*) ;;  # no local model
    *) images+=(ollama/ollama:0.40.5) ;;
  esac
  for img in "${images[@]}"; do
    if docker image inspect "$img" >/dev/null 2>&1; then
      load_image "$img" && echo "  $img" || echo "  $img could not be loaded: the cluster will pull it"
    else
      echo "  $img is not local: the cluster will pull it"
    fi
  done
fi


# ---------------------------------------------------------------- apply
kubectl get namespace "$NAMESPACE" >/dev/null 2>&1 || kubectl create namespace "$NAMESPACE" >/dev/null
NAMESPACE="$NAMESPACE" "$K8S_DIR/scripts/secrets.sh"

if [[ "$OVERLAY" == deepseek-* ]] && \
   [ -z "$(kubectl -n "$NAMESPACE" get secret rag-secrets -o jsonpath='{.data.DEEPSEEK_API_KEY}' 2>/dev/null)" ]; then
  echo "DEEPSEEK_API_KEY is required for overlay '$OVERLAY': put it in .env or export it." >&2
  exit 1
fi

# The Job is immutable: recreate it so a changed model is pulled again.
kubectl -n "$NAMESPACE" delete job ollama-pull --ignore-not-found >/dev/null

# `$patch: delete` only removes them from the rendered output; `kubectl apply` does not prune
# resources that already exist, so delete the local model explicitly when it is not used.
case "$OVERLAY" in
  deepseek-*)
    kubectl -n "$NAMESPACE" delete deployment/ollama service/ollama pvc/ollama-models \
      --ignore-not-found >/dev/null
    ;;
esac

kubectl apply -k "$GEN"

# ConfigMap values are read at pod start. Restarting is opt-in because it can interrupt an
# indexing run (use it after changing the ConfigMap, when the scheduler is idle):
#   RESTART=1 ./deploy/k8s/scripts/deploy.sh
if [ "${RESTART:-0}" = 1 ]; then
  kubectl -n "$NAMESPACE" rollout restart \
    deployment/api deployment/scheduler deployment/embeddings deployment/nginx >/dev/null
fi

for target in \
  statefulset/postgres \
  statefulset/qdrant \
  deployment/embeddings \
  deployment/api \
  deployment/scheduler \
  deployment/nginx; do
  echo "Waiting for $target..."
  kubectl -n "$NAMESPACE" rollout status "$target" --timeout=900s
done

if kubectl -n "$NAMESPACE" get deployment ollama >/dev/null 2>&1; then
  echo "Waiting for deployment/ollama..."
  kubectl -n "$NAMESPACE" rollout status deployment/ollama --timeout=300s
  echo "Waiting for the Ollama model (first run downloads it)..."
  if kubectl -n "$NAMESPACE" wait --for=condition=complete job/ollama-pull --timeout=1800s; then
    echo "Model ready."
  else
    echo "The model is still downloading. Check: kubectl -n $NAMESPACE logs job/ollama-pull" >&2
  fi
fi

echo
kubectl -n "$NAMESPACE" get pods
if is_kind_overlay; then
  echo
  echo "Entry point: $BASE_URL"
fi
